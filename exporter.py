def export_multi_sheet_excel(cleaned_df: pd.DataFrame, profiler_summary: pd.DataFrame = None) -> bytes:
    """Exports an analytical Excel workbook containing the clean dataset plus metadata."""
    buffer = io.BytesIO()
    with pd.ExcelWriter(buffer, engine="openpyxl") as writer:
        cleaned_df.to_excel(writer, sheet_name="Cleaned_Data", index=False)
        if profiler_summary is not None:
            profiler_summary.to_excel(writer, sheet_name="Data_Dictionary", index=False)
        
        # Add correlation sheet if numeric
        num_cols = cleaned_df.select_dtypes("number")
        if len(num_cols.columns) >= 2:
            num_cols.corr().to_excel(writer, sheet_name="Correlation_Matrix")
            
    return buffer.getvalue()
